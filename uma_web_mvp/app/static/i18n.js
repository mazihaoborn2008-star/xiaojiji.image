  const dictionaries = {zh: ZH, en: EN};

  function normalize(lang) {
    return lang === 'en' ? 'en' : 'zh';
  }

  function getLang() {
    try { return normalize(localStorage.getItem(STORAGE_KEY)); } catch (_) { return 'zh'; }
  }

  function format(text, params = {}) {
    return String(text).replace(/\{(\w+)\}/g, (_, key) => params[key] ?? '');
  }

  function t(key, fallback, params) {
    const lang = getLang();
    const text = dictionaries[lang]?.[key] ?? dictionaries.zh[key] ?? fallback ?? key;
    return format(text, params);
  }

  function translateMessage(message) {
    if (!message) return '';
    const key = serverMap[String(message).trim()];
    return key ? t(key, message) : message;
  }

  function setLang(lang) {
    const next = normalize(lang);
    try { localStorage.setItem(STORAGE_KEY, next); } catch (_) {}
    document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
    apply(document);
    window.dispatchEvent(new CustomEvent('uma:langchange', {detail: {lang: next}}));
  }

  function toggleLang() {
    setLang(getLang() === 'en' ? 'zh' : 'en');
  }

  function apply(root = document) {
    const lang = getLang();
    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n, el.textContent);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder, el.getAttribute('placeholder') || ''));
    });
    root.querySelectorAll('[data-i18n-value]').forEach((el) => {
      el.value = t(el.dataset.i18nValue, el.value || '');
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.dataset.i18nTitle, el.getAttribute('title') || ''));
    });
    root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
      el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel, el.getAttribute('aria-label') || ''));
    });
    root.querySelectorAll('[data-lang-toggle]').forEach((el) => {
      el.textContent = t('lang.toggle');
      el.setAttribute('aria-label', t('lang.toggle'));
    });
  }

  document.addEventListener('click', (event) => {
    const button = event.target.closest?.('[data-lang-toggle]');
    if (!button) return;
    event.preventDefault();
    toggleLang();
  });

  // Universal back-to-home handler for all sub-pages
  document.addEventListener('click', (event) => {
    const back = event.target.closest?.('[data-back-home]');
    if (!back) return;
    event.preventDefault();
    window.location.href = '/';
  });

  document.addEventListener('DOMContentLoaded', () => apply(document));

  window.UmaI18n = {t, apply, getLang, setLang, toggleLang, translateMessage};
